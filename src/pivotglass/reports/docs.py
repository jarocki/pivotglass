"""Generate the report reference under ``docs/reports/`` from the definitions (#52).

The pages are derived surfaces: ``scripts/gen_report_docs.py`` writes them,
and ``tests/test_report_types.py`` and ``scripts/check_documentation.py`` fail
when the files on disk differ from what the definitions produce.
"""

from __future__ import annotations

from collections import defaultdict

from pivotglass.reports.claims import REPORT_PREDICATES
from pivotglass.reports.contract import (
    CONFIDENCE_DEFINITIONS,
    CONTROL_STATUS_DEFINITIONS,
    GAP_RULE,
    GAP_SCORE_SCALE,
    INFORMATION_CREDIBILITY_LABELS,
    LIKELIHOOD_RANGES,
    PAP_DEFINITIONS,
    PROVENANCE_LABELS,
    SEVERITY_DEFINITIONS,
    SOURCE_RELIABILITY_LABELS,
    TLP_DEFINITIONS,
    likelihood_phrase,
    pap_label,
    tlp_label,
)
from pivotglass.reports.elements import load_builtin_elements
from pivotglass.reports.elements.planned import PLANNED
from pivotglass.reports.pir import CATEGORIES, LEVELS
from pivotglass.reports.registry import DOMAIN_LABELS, ReportDomain, ReportType, report_types
from pivotglass.reports.rubrics import CAPABILITY_AXES

GENERATED = "<!-- Generated by scripts/gen_report_docs.py from src/pivotglass/reports/. Do not edit. -->"
_PROVENANCE_MEANING = {
    "evidence": "Collected and cited; with no citations the section is empty.",
    "method": "A deterministic computation over evidence; names the method and its version.",
    "analyst": "Written by the analyst; shows the author and time.",
    "model_draft": "Drafted by a model from cited evidence and labelled until the analyst accepts it. "
    "A report with pending drafts can only be issued as DRAFT.",
    "org_input": "Organisation data Pivotglass cannot collect. When absent it is shown as missing, "
    "never filled by a model.",
}


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _element_row(item_id: str) -> tuple[str, str, str, str]:
    built = load_builtin_elements()
    if item_id in built:
        spec = built[item_id]
        return spec.title, " + ".join(PROVENANCE_LABELS[p] for p in spec.provenance), ", ".join(spec.authorities), "built"
    planned = PLANNED[item_id]
    return (
        planned.title,
        " + ".join(PROVENANCE_LABELS[p] for p in planned.provenance),
        ", ".join(planned.authorities),
        f"#{planned.issue}",
    )


def _description(item_id: str) -> str:
    built = load_builtin_elements()
    return built[item_id].description if item_id in built else PLANNED[item_id].description


def _suggested_by(type_id: str) -> list[str]:
    found = []
    for definition in CATEGORIES.values():
        for level, ids in definition.report_types.items():
            if type_id in ids:
                found.append(f"{definition.label} ({LEVELS[level].label.lower()})")
    return found


def type_page(t: ReportType) -> str:
    all_types = report_types()
    number = f"Type {t.number} · " if t.number else ""
    tier = LEVELS[t.tier].label if t.tier else "Any"
    status = (
        "Built: `report " + t.id + "` renders it."
        if t.available
        else "Defined, not built yet. Its sections arrive with "
        + ", ".join(f"#{n}" for n in t.building_issues)
        + "; until then `report "
        + t.id
        + "` explains what is missing and renders nothing."
    )
    lines = [
        GENERATED,
        "",
        f"# {t.title}",
        "",
        f"{number}{DOMAIN_LABELS[t.domain]} · `{t.id}` · ID prefix `PG-{t.code}-`",
        "",
        _cell(t.purpose),
        "",
        f"**Status:** {status}",
        "",
    ]
    if t.use_when:
        lines += [f"**Use it when:** {_cell(t.use_when)}", ""]
    lines += [
        "| | |",
        "|---|---|",
        f"| Audience | {_cell(', '.join(t.audience))} |",
        f"| Tier | {tier} |",
        f"| Default marking | {tlp_label(t.default_marking.tlp)} · {pap_label(t.default_marking.pap)} |",
        f"| Valid for | {f'{t.validity_days} days from issue' if t.validity_days else 'No expiry (historical record)'} |",
        f"| Formats | {', '.join(f.value for f in t.formats)} |",
    ]
    suggested = _suggested_by(t.id)
    if suggested:
        lines.append(f"| Suggested for PIRs | {_cell('; '.join(suggested))} |")
    if t.related:
        links = ", ".join(f"[{all_types[r].title}]({r}.md)" for r in t.related)
        lines.append(f"| Related types | {links} |")
    lines += [
        "",
        "## Sections",
        "",
        "In order. A required section with no content makes the report **Incomplete**, and the report "
        "names it. Every report has the header, the PIR verdict, Gaps and Limitations, and Sources.",
        "",
        "| # | Section | Required | Provenance | Built from | Status |",
        "|---:|---|---|---|---|---|",
    ]
    for index, item in enumerate(t.elements, 1):
        title, provenance, authorities, built = _element_row(item.id)
        lines.append(
            f"| {index} | {title} (`{item.id}`) | {'yes' if item.required else 'optional'} | "
            f"{provenance} | {_cell(authorities)} | {built} |"
        )
    lines += ["", "## What each section must say", ""]
    for item in t.elements:
        title = _element_row(item.id)[0]
        text = _cell(item.guidance) if item.guidance else _cell(_description(item.id))
        lines.append(f"- **{title}.** {text}")
    lines += [
        "",
        "## Rules every report follows",
        "",
        "- Indicator values are defanged in Markdown and unchanged in JSON, STIX and rule files.",
        "- Each judgment states a likelihood term and, separately, a confidence level "
        "([vocabularies](README.md#vocabularies)).",
        "- Each section shows its provenance; each source shows its Admiralty rating.",
        "- Examples use reserved names and addresses only (RFC 2606, RFC 5737, RFC 3849).",
        "",
    ]
    return "\n".join(lines)


def index_page() -> str:
    types = report_types()
    by_domain: dict[ReportDomain, list[ReportType]] = defaultdict(list)
    for t in types.values():
        by_domain[t.domain].append(t)
    lines = [
        GENERATED,
        "",
        "# Report types",
        "",
        "Pivotglass assembles reports from sections that each state where their content comes from. "
        "Preview any built type with `report <type>`, issue it with `report issue <type>`, and list "
        "the types with `report types`. The design is in "
        "[architecture/REPORTS.md](../architecture/REPORTS.md).",
        "",
    ]
    for domain in ReportDomain:
        if not by_domain.get(domain):
            continue
        lines += [f"## {DOMAIN_LABELS[domain]}", "", "| # | Type | Tier | Audience | Marking | Status |", "|---:|---|---|---|---|---|"]
        for t in by_domain[domain]:
            status = "built" if t.available else "needs " + ", ".join(f"#{n}" for n in t.building_issues)
            lines.append(
                f"| {t.number or '—'} | [{t.title}]({t.id}.md) | {LEVELS[t.tier].label if t.tier else 'Any'} | "
                f"{_cell(', '.join(t.audience))} | {tlp_label(t.default_marking.tlp)} · "
                f"{pap_label(t.default_marking.pap)} | {status} |"
            )
        lines.append("")
    lines += ["## Provenance classes", "", "| Class | Meaning |", "|---|---|"]
    lines += [f"| {PROVENANCE_LABELS[k]} | {_PROVENANCE_MEANING[k.value]} |" for k in PROVENANCE_LABELS]
    lines += [
        "",
        "## Analyst claims",
        "",
        "Actor sections (identity, motivation, victimology, timeline, arsenal, capability) read structured claims "
        "you record in the analytic ledger. The subject is `actor:<name>`; name it in the report command when more "
        "than one actor has claims (`report threat-actor-profile actor:<name>`).",
        "",
        "```text",
        "analysis claim judgment actor:<name> <predicate> <value> | <statement with its basis>",
        "```",
        "",
        "| Predicate | Meaning |",
        "|---|---|",
    ]
    lines += [f"| `{k}` | {v} |" for k, v in REPORT_PREDICATES.items()]
    lines += ["", f"Capability axes for `capability:<axis>`: {', '.join(f'`{k}`' for k in CAPABILITY_AXES)}.", ""]
    lines += ["## Vocabularies", "", "### Likelihood (ICD 203) and confidence", ""]
    lines += [f"- {likelihood_phrase(term)}" for term in LIKELIHOOD_RANGES]
    lines += [""]
    lines += [f"- **{level.value.title()} confidence:** {text}" for level, text in CONFIDENCE_DEFINITIONS.items()]
    lines += ["", "Likelihood is how probable the event is; confidence is how good the evidence is.", ""]
    lines += ["### Markings", "", "| Marking | Meaning |", "|---|---|"]
    lines += [f"| {tlp_label(k)} | {v} |" for k, v in TLP_DEFINITIONS.items()]
    lines += [f"| {pap_label(k)} | {v} |" for k, v in PAP_DEFINITIONS.items()]
    lines += ["", "### Source ratings (Admiralty)", "", "| Reliability | | Credibility | |", "|---|---|---|---|"]
    for (r, rl), (c, cl) in zip(SOURCE_RELIABILITY_LABELS.items(), INFORMATION_CREDIBILITY_LABELS.items()):
        lines.append(f"| {r.value} | {rl} | {c.value} | {cl} |")
    lines += ["", "### Severity", "", "| Severity | Meaning |", "|---|---|"]
    lines += [f"| {k.value.title()} | {v} |" for k, v in SEVERITY_DEFINITIONS.items()]
    lines += ["", "### Control status", "", "| Status | Meaning |", "|---|---|"]
    lines += [f"| {k.value.replace('_', ' ').capitalize()} | {v} |" for k, v in CONTROL_STATUS_DEFINITIONS.items()]
    lines += ["", "### Coverage gap status", "", "Each dimension is scored 0 to 2:", ""]
    lines += [f"- **{name.title()}:** {'; '.join(scale)}." for name, scale in GAP_SCORE_SCALE.items()]
    lines += ["", f"Rule: {GAP_RULE}", ""]
    return "\n".join(lines)


def reference_docs() -> dict[str, str]:
    """Every generated page, keyed by path relative to ``docs/reports/``."""

    pages = {"README.md": index_page()}
    pages.update({f"{t.id}.md": type_page(t) for t in report_types().values()})
    return pages
